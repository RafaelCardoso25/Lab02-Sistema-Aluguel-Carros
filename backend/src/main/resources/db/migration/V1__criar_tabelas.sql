CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(60) NOT NULL UNIQUE,
    senha_hash VARCHAR(100) NOT NULL,
    nome VARCHAR(120) NOT NULL
);

CREATE TABLE clientes (
    id BIGINT PRIMARY KEY REFERENCES usuarios (id),
    rg VARCHAR(20) NOT NULL UNIQUE,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    endereco VARCHAR(200) NOT NULL,
    profissao VARCHAR(80) NOT NULL
);

CREATE TABLE rendimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes (id),
    entidade_empregadora VARCHAR(120) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0)
);

CREATE TABLE agentes (
    id BIGINT PRIMARY KEY REFERENCES usuarios (id),
    cnpj VARCHAR(14) NOT NULL UNIQUE
);

CREATE TABLE empresas (
    id BIGINT PRIMARY KEY REFERENCES agentes (id)
);

CREATE TABLE bancos (
    id BIGINT PRIMARY KEY REFERENCES agentes (id)
);

CREATE TABLE automoveis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL UNIQUE,
    ano INTEGER NOT NULL,
    marca VARCHAR(60) NOT NULL,
    modelo VARCHAR(60) NOT NULL,
    placa VARCHAR(7) NOT NULL UNIQUE,
    proprietario_id BIGINT NOT NULL REFERENCES usuarios (id)
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes (id),
    automovel_id BIGINT NOT NULL REFERENCES automoveis (id),
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    parecer VARCHAR(500),
    avaliado_por_id BIGINT REFERENCES agentes (id),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK (data_fim >= data_inicio)
);

CREATE TABLE contratos_credito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    banco_id BIGINT NOT NULL REFERENCES bancos (id),
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    taxa_juros_mensal NUMERIC(5, 2) NOT NULL CHECK (taxa_juros_mensal >= 0),
    parcelas INTEGER NOT NULL CHECK (parcelas > 0)
);

CREATE TABLE contratos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedidos (id),
    agente_id BIGINT NOT NULL REFERENCES agentes (id),
    tipo VARCHAR(30) NOT NULL,
    valor NUMERIC(12, 2) NOT NULL CHECK (valor > 0),
    data_assinatura DATE NOT NULL,
    contrato_credito_id BIGINT UNIQUE REFERENCES contratos_credito (id)
);

CREATE INDEX idx_pedidos_cliente ON pedidos (cliente_id);
CREATE INDEX idx_pedidos_automovel ON pedidos (automovel_id);
CREATE INDEX idx_rendimentos_cliente ON rendimentos (cliente_id);
